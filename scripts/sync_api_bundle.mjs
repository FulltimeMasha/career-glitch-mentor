// scripts/sync_api_bundle.mjs
// ---------------------------------------------------------------------------
// Copies the Mentor API into the careerglitch site tree for deployment:
//   careerglitch-site/api/mentor.js          <- api/mentor.js (entry shim)
//   careerglitch-site/api/_lib/mentor-core.mjs
//   careerglitch-site/api/_lib/engine-bridge.mjs   (bundle variant)
//   careerglitch-site/api/_lib/engine/*.mjs  <- engine/*
//   careerglitch-site/api/_lib/engine/stages.json
// Prints the file list (site-relative) for deploy_patch.py.
// Run from repo root:  node scripts/sync_api_bundle.mjs
// ---------------------------------------------------------------------------

import { cpSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = join(homedir(), 'workspace', 'careerglitch-site');
const LIB = join(SITE, 'api', '_lib');

mkdirSync(join(LIB, 'engine'), { recursive: true });

const written = [];
const put = (siteRel, content) => {
  writeFileSync(join(SITE, siteRel), content);
  written.push(siteRel);
};

// Entry shim
put('api/mentor.js', readFileSync(join(ROOT, 'api', 'mentor.js'), 'utf8'));

// Core (imports './engine-bridge.mjs' — same in both layouts)
put('api/_lib/mentor-core.mjs', readFileSync(join(ROOT, 'server', 'mentor-core.mjs'), 'utf8'));

// Bundle bridge: engine lives at ./engine/ relative to _lib/
put('api/_lib/engine-bridge.mjs', `// GENERATED by scripts/sync_api_bundle.mjs — bundle variant of
// server/engine-bridge.mjs with paths relative to api/_lib/.
export {
  createSession,
  applyCddq,
  stagePrompt,
  applyStage,
  applyPerceivedFit,
  generateReport,
  deserializeSession,
  serializeSession,
} from './engine/interview.mjs';
export { metaRespond, MODELS } from './engine/llm.mjs';
export { loadProfessions, buildProfessions, ROADMAP_FILE_NAMES } from './engine/professions.mjs';
`);

// Engine files (verbatim copies)
for (const f of ['interview.mjs', 'llm.mjs', 'professions.mjs', 'scoring.mjs', 'stages.json']) {
  cpSync(join(ROOT, 'engine', f), join(LIB, 'engine', f));
  written.push(`api/_lib/engine/${f}`);
}

// WS2 data: the O*NET import rides in the bundle at _lib/data/ so the
// bundled engine finds it at ../data/onet-import.json (same relative
// path as the repo layout).
mkdirSync(join(LIB, 'data'), { recursive: true });
cpSync(join(ROOT, 'data', 'onet-import.json'), join(LIB, 'data', 'onet-import.json'));
written.push('api/_lib/data/onet-import.json');

console.log(written.join('\n'));

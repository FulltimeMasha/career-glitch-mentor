// scripts/sync_api_bundle.mjs
// ---------------------------------------------------------------------------
// Copies the Mentor API into the careerglitch site tree for deployment:
//   careerglitch-site/api/mentor.js          <- api/mentor.js (entry shim)
//   careerglitch-site/api/_lib/mentor-core.mjs
//   careerglitch-site/api/_lib/engine-bridge.mjs   (bundle variant)
//   careerglitch-site/api/_lib/engine/*.mjs  <- engine/*
//   careerglitch-site/api/_lib/engine/stages.json
// Prints the file list (site-relative) for deploy_patch.py.
// Run from repo root:  node scripts/sync_api_bundle.mjs
// ---------------------------------------------------------------------------

import { cpSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = join(homedir(), 'workspace', 'careerglitch-site');
const LIB = join(SITE, 'api', '_lib');

mkdirSync(join(LIB, 'engine'), { recursive: true });

const written = [];
const put = (siteRel, content) => {
  writeFileSync(join(SITE, siteRel), content);
  written.push(siteRel);
};

// Entry shim
put('api/mentor.js', readFileSync(join(ROOT, 'api', 'mentor.js'), 'utf8'));

// Core (imports './engine-bridge.mjs' — same in both layouts)
put('api/_lib/mentor-core.mjs', readFileSync(join(ROOT, 'server', 'mentor-core.mjs'), 'utf8'));

// Bundle bridge: engine lives at ./engine/ relative to _lib/
put('api/_lib/engine-bridge.mjs', `// GENERATED by scripts/sync_api_bundle.mjs — bundle variant of
// server/engine-bridge.mjs with paths relative to api/_lib/.
export {
  createSession,
  applyCddq,
  stagePrompt,
  applyStage,
  applyPerceivedFit,
  generateReport,
  generateVerifiedReport,
  buildChecklist,
  deserializeSession,
  serializeSession,
} from './engine/interview.mjs';
export { metaRespond, MODELS } from './engine/llm.mjs';
export { loadProfessions, buildProfessions, ROADMAP_FILE_NAMES } from './engine/professions.mjs';
`);

// Engine files (verbatim copies)
for (const f of ['interview.mjs', 'llm.mjs', 'professions.mjs', 'scoring.mjs', 'verify.mjs', 'stages.json']) {
  cpSync(join(ROOT, 'engine', f), join(LIB, 'engine', f));
  written.push(`api/_lib/engine/${f}`);
}

// WS2 data: the O*NET import rides in the bundle at _lib/data/ so the
// bundled engine finds it at ../data/. The connector upload path caps a
// single file at ~90 KB (OS argv limit on the base64 payload), so the
// import ships as compact shards of <= 80 KB which the loader merges
// back (see readOnetImport in engine/professions.mjs). Shard 01 also
// carries the meta block.
import { rmSync } from 'node:fs';
mkdirSync(join(LIB, 'data'), { recursive: true });
try { rmSync(join(LIB, 'data', 'onet-import.json')); } catch { /* not present */ }
for (const stale of (await import('node:fs')).readdirSync(join(LIB, 'data'))) {
  if (/^onet-import-\d+\.json$/.test(stale)) rmSync(join(LIB, 'data', stale));
}
const imp = JSON.parse(readFileSync(join(ROOT, 'data', 'onet-import.json'), 'utf8'));
const SHARD_LIMIT = 80000;
const slugs = Object.keys(imp.professions).sort();
let shardIdx = 0;
let shard = null;
const flushShard = () => {
  if (!shard) return;
  shardIdx += 1;
  const name = `onet-import-${String(shardIdx).padStart(2, '0')}.json`;
  writeFileSync(join(LIB, 'data', name), JSON.stringify(shard));
  written.push(`api/_lib/data/${name}`);
  shard = null;
};
for (const slug of slugs) {
  const entry = imp.professions[slug];
  const entrySize = Buffer.byteLength(JSON.stringify(entry)) + slug.length + 4;
  if (!shard) shard = shardIdx === 0 ? { meta: imp.meta, professions: {} } : { professions: {} };
  const base = Buffer.byteLength(JSON.stringify(shard));
  if (Object.keys(shard.professions).length && base + entrySize > SHARD_LIMIT) {
    flushShard();
    shard = { professions: {} };
  }
  shard.professions[slug] = entry;
}
flushShard();

console.log(written.join('\n'));
